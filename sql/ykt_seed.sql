-- ############################################################################
-- Part 3 · 自洽校验（四条，跑完都应该是 0 行）
-- ############################################################################
--
-- 种子数据最容易出的错不是写不进去，是"写进去但对不上"。
-- 下面四条把能算的关系全算一遍，答辩前跑一次，能挡掉大部分当场被问住的场面。

-- 校验 1：每个卡户的余额 = 其流水的变动合计
SELECT '校验1 余额与流水不符' AS chk, a.id, a.stu_name, a.bal, IFNULL(SUM(f.chg_amt), 0) AS flow_sum
FROM card_acct a
LEFT JOIN acct_flow f ON f.acct_id = a.id
GROUP BY a.id, a.stu_name, a.bal
HAVING a.bal <> IFNULL(SUM(f.chg_amt), 0);

-- 校验 2：账单三额关系 pay_amt = amt - rebate_amt
SELECT '校验2 三额关系不平' AS chk, id, bill_no, amt, rebate_amt, pay_amt
FROM pay_bill
WHERE pay_amt <> amt - rebate_amt;

-- 校验 3：消费单的账单行合计 = 账单金额
SELECT '校验3 明细与账单不符' AS chk, b.id, b.bill_no, b.amt, IFNULL(SUM(l.amt), 0) AS line_amt
FROM pay_bill b
LEFT JOIN bill_line l ON l.bill_id = b.id
WHERE b.kind = 2
GROUP BY b.id, b.bill_no, b.amt
HAVING b.amt <> IFNULL(SUM(l.amt), 0);

-- 校验 4：结算单的系统侧笔数/金额 = 当天该机具的真实汇总
--   期望结果：两行都显示 ok；D003 的 diff 为 2 是「故意造的差异」，不是错误。
SELECT
  s.settle_date, s.dev_no, s.cnt, s.dev_cnt, (s.dev_cnt - s.cnt) AS diff,
  s.amt AS settle_amt,
  (SELECT COUNT(*) FROM pay_bill b
     WHERE b.dev_no = s.dev_no AND DATE(b.created_at) = s.settle_date AND b.kind = 2) AS real_cnt,
  (SELECT IFNULL(SUM(b.amt), 0) FROM pay_bill b
     WHERE b.dev_no = s.dev_no AND DATE(b.created_at) = s.settle_date AND b.kind = 2) AS real_amt
FROM settle_bill s;


